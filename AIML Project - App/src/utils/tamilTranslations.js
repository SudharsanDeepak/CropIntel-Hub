export const getTamilName = (englishName) => {
  if (!englishName) return ""
  const trimmed = englishName.trim()
  if (TAMIL_PRODUCT_NAMES[trimmed]) {
    return TAMIL_PRODUCT_NAMES[trimmed]
  }

  // Case-insensitive lookup fallback
  const lower = trimmed.toLowerCase()
  const key = Object.keys(TAMIL_PRODUCT_NAMES).find(
    (k) => k.toLowerCase() === lower
  )
  return key ? TAMIL_PRODUCT_NAMES[key] : ""
}
